from machine import I2C, Pin

# ── I2C 設定 ─────────────────────────────────────────────────────────
# Grove シールドの I2C1 コネクタ = SCL: GP7 / SDA: GP6
# I2C は SDA（データ）と SCL（タイミング）の2本で、相手を「アドレス」で呼び分ける
I2C_ID = 1
SCL_PIN = 7
SDA_PIN = 6
I2C_FREQ = 400_000   # 400kHz（I2C のファストモード）

# ── 初期化 ───────────────────────────────────────────────────────────
i2c = I2C(I2C_ID, scl=Pin(SCL_PIN), sda=Pin(SDA_PIN), freq=I2C_FREQ)

print("I2C スキャン 開始")

# ── スキャン ─────────────────────────────────────────────────────────
# scan() は、返事をしてきた相手のアドレスをリストで返す（LCD だけなら [62]）
# 10進数のままだと分かりにくいので、hex() で 0x3e の形にして表示する
found = i2c.scan()
if found:
    for addr in found:
        print(f"見つかりました: {hex(addr)}")
else:
    # 確認の順番: ① I2C0 と I2C1 の取り違え ② ケーブルの差し込み ③ 電圧スイッチ
    print("何も見つかりませんでした。ケーブルと差し込み口を確かめてください")
