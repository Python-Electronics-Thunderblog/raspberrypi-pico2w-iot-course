from machine import Pin
import dht

# ── ピン設定 ─────────────────────────────────────────────────────────
# Grove シールドの D16 コネクタ = GP16
DHT11_PIN = 16

# ── センサー初期化 ───────────────────────────────────────────────────
# DHT11 は信号線1本で温度と湿度を送ってくる（I2C ではない）
# dht モジュールは MicroPython に最初から入っているので、追加インストールは不要
sensor = dht.DHT11(Pin(DHT11_PIN))

print("DHT11 温湿度センサー 1回読み取り")

# ── 読み取り ─────────────────────────────────────────────────────────
# 2段構え: measure() でセンサーから40ビットを受け取り、
#          temperature() / humidity() で受け取った値を取り出す
sensor.measure()

# DHT11 は整数しか返さない（小数点以下は出ない。故障ではない）
# 精度は 温度 ±2℃ / 湿度 ±5%RH。「ざっくり測る用途」のセンサー
print(f"温度: {sensor.temperature()} ℃")
print(f"湿度: {sensor.humidity()} %")

